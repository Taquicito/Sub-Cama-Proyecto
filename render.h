static const unsigned char GLYPH_INV_Q[8] = { 0x00,0x0C,0x00,0x0C,0x18,0x30,0x33,0x1E };   /* ¿ */
static const unsigned char GLYPH_INV_E[8] = { 0x00,0x18,0x00,0x18,0x18,0x3C,0x3C,0x18 };   /* ¡ */

/* Siguiente caracter Unicode de una cadena UTF-8 */
static uint32_t u8next(const char **ps) {
    const unsigned char *p = (const unsigned char *)*ps;
    uint32_t c = *p++;
    if (c >= 0xC0 && c < 0xE0 && (p[0] & 0xC0) == 0x80) { c = ((c & 0x1F) << 6) | (p[0] & 0x3F); p++; }
    else if (c >= 0xE0 && c < 0xF0 && (p[0] & 0xC0) == 0x80 && (p[1] & 0xC0) == 0x80) { c = '?'; p += 2; }
    else if (c >= 0x80) c = '?';
    *ps = (const char *)p;
    return c;
}
static int u8len(const char *s) { int n = 0; while (*s) { u8next(&s); n++; } return n; }
/* Rellena con espacios hasta 'width' caracteres (UTF-8 seguro) */
static void padf(char *dst, int dstsz, const char *s, int width) {
    int n = 0, k = 0;
    while (*s && k < dstsz - 1) { const char *q = s; u8next(&s); while (q < s && k < dstsz - 1) dst[k++] = *q++; n++; }
    while (n < width && k < dstsz - 1) { dst[k++] = ' '; n++; }
    dst[k] = 0;
}

static void gfx_char(int x, int y, uint32_t cp, pix c, int s) {
    unsigned char g[8];
    uint32_t base = cp; int acc = 0, cap = 0;
    switch (cp) {
        case 0xE1: base = 'a'; acc = 1; break;           case 0xC1: base = 'A'; acc = 1; cap = 1; break;
        case 0xE9: base = 'e'; acc = 1; break;           case 0xC9: base = 'E'; acc = 1; cap = 1; break;
        case 0xED: base = 'i'; acc = 1; break;           case 0xCD: base = 'I'; acc = 1; cap = 1; break;
        case 0xF3: base = 'o'; acc = 1; break;           case 0xD3: base = 'O'; acc = 1; cap = 1; break;
        case 0xFA: base = 'u'; acc = 1; break;           case 0xDA: base = 'U'; acc = 1; cap = 1; break;
        case 0xFC: base = 'u'; acc = 3; break;           case 0xDC: base = 'U'; acc = 3; cap = 1; break;
        case 0xF1: base = 'n'; acc = 2; break;           case 0xD1: base = 'N'; acc = 2; cap = 1; break;
        default: break;
    }
    if (cp == 0xBF) memcpy(g, GLYPH_INV_Q, 8);
    else if (cp == 0xA1) memcpy(g, GLYPH_INV_E, 8);
    else if (base >= 32 && base <= 126) memcpy(g, FONT8[base - 32], 8);
    else memcpy(g, FONT8['?' - 32], 8);
    if (base == 'i' && acc == 1) g[0] = 0;               /* la i acentuada pierde el punto */
    for (int j = 0; j < 8; j++)
        for (int i = 0; i < 8; i++)
            if ((g[j] >> i) & 1) gfx_rect(x + i * s, y + j * s, s, s, c);
    if (acc) {
        static const unsigned char AC[4][2] = { { 0, 0 }, { 0x10, 0x08 }, { 0x6E, 0x3B }, { 0x12, 0x00 } };
        int dy = cap ? -2 : 0;
        for (int r = 0; r < 2; r++)
            for (int i = 0; i < 8; i++)
                if ((AC[acc][r] >> i) & 1) gfx_rect(x + i * s, y + (dy + r) * s, s, s, c);
    }
}
/* Dibuja los primeros n caracteres (no bytes) de la cadena; '\n' = salto de linea */
static void gfx_text_n(int x, int y, const char *s, int n, pix c, int sc) {
    int cx = x, cy = y;
    while (*s && n > 0) {
        uint32_t cp = u8next(&s); n--;
        if (cp == '\n') { cx = x; cy += 10 * sc; continue; }
        gfx_char(cx, cy, cp, c, sc);
        cx += 8 * sc;
    }
}
static void gfx_text(int x, int y, const char *s, pix c, int sc) { gfx_text_n(x, y, s, 1 << 30, c, sc); }
static int text_w(const char *s) {                      /* ancho de la linea mas larga a escala 1 */
    int best = 0, cur = 0;
    while (*s) { uint32_t cp = u8next(&s); if (cp == '\n') { if (cur > best) best = cur; cur = 0; } else cur++; }
    if (cur > best) best = cur;
    return best * 8;
}
static void gfx_text_c(int y, const char *s, pix c, int sc) { gfx_text((SCR_W - text_w(s) * sc) / 2, y, s, c, sc); }
static void gfx_text_sh(int x, int y, const char *s, pix c, int sc) { gfx_text(x + sc, y + sc, s, BLACK, sc); gfx_text(x, y, s, c, sc); }

/* ---------- Sprites 8x8: filas de texto; '1'..'9' = indice de paleta ---------- */
static void gfx_sprite_n(const char *const *rows, int w, int h, const pix *pal, int x, int y, int s, int flip) {
    for (int j = 0; j < h; j++)
        for (int i = 0; i < w; i++) {
            char ch = rows[j][flip ? w - 1 - i : i];
            if (ch >= '1' && ch <= '9') gfx_rect(x + i * s, y + j * s, s, s, pal[ch - '1']);
        }
}
static void gfx_sprite(const char *const *rows, const pix *pal, int x, int y, int s, int flip) {
    gfx_sprite_n(rows, 8, 8, pal, x, y, s, flip);
}

/* Barra de estado (vida, SP, etc.) */
static void gfx_bar(int x, int y, int w, int h, int v, int mx, pix fg, pix bg) {
    gfx_rect(x, y, w, h, bg);
    if (mx > 0 && v > 0) { int fw = w * v / mx; if (fw < 1) fw = 1; if (fw > w) fw = w; gfx_rect(x, y, fw, h, fg); }
}
/* Estatica blanca (n puntos de ruido) */
static void gfx_static(int n, int vmin, int vmax) {
    for (int i = 0; i < n; i++) {
        int v = vmin + (int)(rnd() % (uint32_t)(vmax - vmin + 1));
        gfx_px((int)(rnd() % SCR_W), (int)(rnd() % SCR_H), rgb(v, v, v));
    }
}

